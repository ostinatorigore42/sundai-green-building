def layout(text, glyphs=GLYPHS):
    """Text -> (width, [(row, col, char_index, rgb_or_None)]) of lit cells, 1 blank column between glyphs.

    '<3' renders as a heart and '{name}' as a coloured icon from icons.py (rgb set);
    text cells have rgb None so the caller picks the colour. Unknown characters are skipped.
    """
    cells, x, i = [], 0, 0
    while i < len(text):
        rgb_of = None
        if text[i] == "{" and "}" in text[i:]:
            key = text[i:text.index("}", i) + 1]
            glyph = icons.ICONS.get(key[1:-1].lower())
            rgb_of = icons.COLORS
        else:
            key = "<3" if text.startswith("<3", i) else text[i]
            glyph = glyphs.get(key.upper())
        if glyph:
            for r, line in enumerate(glyph):
                for c, ch in enumerate(line):
                    if rgb_of is not None and ch in rgb_of:
                        cells.append((r, x + c, i, rgb_of[ch]))
                    elif rgb_of is None and ch == "#":
                        cells.append((r, x + c, i, None))
            x += len(glyph[0]) + 1
        i += len(key)
    return max(x - 1, 0), cells
